// Small narrow deep-blue boat along local Z with glowing hull, bright curled prow at +Z, oar across, soft glow disc beneath; params: length, color
export function build(THREE, p, ctx) {
  const g = new THREE.Group();
  const L = p.length || 3, W = 0.8;
  const col = p.color || '#1c3a7a';
  const hm = ctx.mat(col, { emissive: '#2a58b0', emissiveIntensity: 0.6, side: THREE.DoubleSide });
  const sh = new THREE.Shape();
  sh.moveTo(-L / 2, 0);
  sh.quadraticCurveTo(-L * 0.1, W / 2, L / 2, 0);
  sh.quadraticCurveTo(-L * 0.1, -W / 2, -L / 2, 0);
  const hole = new THREE.Path();
  const l2 = L * 0.42;
  hole.moveTo(-l2, 0);
  hole.quadraticCurveTo(-L * 0.1, W * 0.33, l2, 0);
  hole.quadraticCurveTo(-L * 0.1, -W * 0.33, -l2, 0);
  sh.holes.push(hole);
  const wallG = new THREE.ExtrudeGeometry(sh, { depth: 0.35, bevelEnabled: false });
  wallG.rotateX(-Math.PI / 2);
  wallG.rotateY(-Math.PI / 2);
  g.add(new THREE.Mesh(wallG, hm));
  const bs = new THREE.Shape();
  bs.moveTo(-L / 2, 0);
  bs.quadraticCurveTo(-L * 0.1, W / 2, L / 2, 0);
  bs.quadraticCurveTo(-L * 0.1, -W / 2, -L / 2, 0);
  const bg = new THREE.ShapeGeometry(bs);
  bg.rotateX(-Math.PI / 2);
  bg.rotateY(-Math.PI / 2);
  const bottom = new THREE.Mesh(bg, ctx.mat('#10224a', { emissive: '#1c3a7a', emissiveIntensity: 0.4, side: THREE.DoubleSide }));
  bottom.position.y = 0.08;
  g.add(bottom);
  const pale = ctx.mat('#dfe6ff', { emissive: '#dfe6ff', emissiveIntensity: 0.8 });
  const prow = new THREE.Mesh(new THREE.TorusGeometry(0.28, 0.05, 5, 9, Math.PI * 1.2), pale);
  prow.rotation.y = Math.PI / 2;
  prow.rotation.z = -0.5;
  prow.position.set(0, 0.5, L / 2 - 0.05);
  g.add(prow);
  const stern = new THREE.Mesh(new THREE.ConeGeometry(0.1, 0.4, 5), pale);
  stern.position.set(0, 0.45, -L / 2 + 0.05);
  stern.rotation.x = -0.4;
  g.add(stern);
  const woodM = ctx.mat('#23252f', { emissive: '#3a3f5c', emissiveIntensity: 0.4 });
  const oar = new THREE.Mesh(new THREE.CylinderGeometry(0.025, 0.025, 1.3, 5), woodM);
  oar.rotation.z = Math.PI / 2;
  oar.rotation.y = 0.15;
  oar.position.set(0, 0.4, 0.1);
  g.add(oar);
  const blade = new THREE.Mesh(new THREE.BoxGeometry(0.28, 0.02, 0.14), woodM);
  blade.position.set(0.62, 0.4, 0.07);
  g.add(blade);
  const gt = ctx.dataTexture(64, 64, (u, v) => {
    const d = Math.min(1, Math.hypot(u - 0.5, v - 0.5) * 2);
    const k = Math.pow(1 - d, 2) * 255;
    return [k * 0.56, k * 0.75, k];
  });
  const cg = new THREE.CircleGeometry(1.5, 28);
  cg.rotateX(-Math.PI / 2);
  const glow = new THREE.Mesh(cg, new THREE.MeshBasicMaterial({ map: gt, color: '#8fc0ff', transparent: true, opacity: 0.2, blending: THREE.AdditiveBlending, depthWrite: false, fog: false }));
  glow.position.y = 0.04;
  g.add(glow);
  return g;
}
